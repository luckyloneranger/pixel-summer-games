/** The order glyphs are laid out in the font image, left to right. */
export const GLYPH_ORDER = Object.keys(GLYPHS);

/** Index of a character in GLYPH_ORDER (unknown characters map to '?'). */
const indexByChar = new Map<string, number>(GLYPH_ORDER.map((c, i) => [c, i]));
export function glyphIndex(ch: string): number {
  return indexByChar.get(ch) ?? indexByChar.get(ch.toUpperCase()) ?? indexByChar.get('?')!;
}

/** Width in pixels of a line of text at the given scale. */
export function textWidth(text: string, scale = 1): number {
  return text.length * GLYPH_SIZE * scale;
}
